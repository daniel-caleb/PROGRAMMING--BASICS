// Array Declaration
let fruits = ["apple", "banana", "orange"]; // This is an array declaration and initialization. The array 'fruits' contains three string elements.

// Array Access
console.log(fruits[0]); // This will output the string "apple" to the console.
console.log(fruits[1]); // This will output the string "banana" to the console.
console.log(fruits[2]); // This will output the string "orange" to the console.

// Array Modification
fruits[0] = "grape"; // This will change the first element of the array 'fruits' to "grape".
console.log(fruits[0]); // This will output the string "grape" to the console.

// Array Length
console.log(fruits.length); // This will output the number 3 to the console, which is the length of the array 'fruits'.