// Loops
// 1. For Loop
for (let i = 0; i < 5; i++) { // This is a for loop that will execute the code block inside it 5 times.
    console.log("For Loop: " + i); // This will output the string "For Loop: " followed by the value of 'i' to the console.
}

// 2. While Loop
let j = 0; // This is a variable declaration and assignment. The variable 'j' is assigned the number value 0.
while (j < 5) { // This is a while loop that will execute the code block inside it as long as the condition 'j < 5' is true.
    console.log("While Loop: " + j); // This will output the string "While Loop: " followed by the value of 'j' to the console.
    j++; // This increments the value of 'j' by 1.
}

// 3. Do-While Loop
let k = 0; // This is a variable declaration and assignment. The variable 'k' is assigned the number value 0.
do { // This is a do-while loop that will execute the code block inside it at least once, regardless of whether the condition is true or false.
    console.log("Do-While Loop: " + k); // This will output the string "Do-While Loop: " followed by the value of 'k' to the console.
    k++; // This increments the value of 'k' by 1.
} while (k < 5); // The condition 'k < 5' is checked after each iteration of the loop.