// Creating an array
let numbers = [1, 2, 3, 4, 5]; // This is an array declaration and initialization. The array 'numbers' contains five numeric elements.
console.log(numbers); // This will output the array 'numbers' to the console.
let names = ["Alice", "Bob", "Charlie"]; // This is an array declaration and initialization. The array 'names' contains three string elements.
console.log(names); // This will output the array 'names' to the console.
let mixedArray = [1, "two", true, null]; // This is an array declaration and initialization. The array 'mixedArray' contains elements of different data types.
console.log(mixedArray); // This will output the array 'mixedArray' to the console.

// Accessing array elements
console.log(numbers[3]); // This will output the number 4 to the console, which is the fourth element of the array 'numbers'.
console.log(names[1]); // This will output the string "Bob" to the console, which is the second element of the array 'names'.
console.log(mixedArray[2]); // This will output the boolean value true to the console, which is the third element of the array 'mixedArray'.
console.log(numbers.reverse()); // This will output the reversed array 'numbers' to the console.

// Modifying array elements
numbers[0] = 10; // This will change the first element of the array 'numbers' to 10.
console.log(numbers); // This will output the modified array 'numbers' to the console.
names[2] = "David"; // This will change the third element of the array 'names' to "David".
console.log(names); // This will output the modified array 'names' to the console.
mixedArray[1] = "three";    // This will change the second element of the array 'mixedArray' to "three".
console.log(mixedArray); // This will output the modified array 'mixedArray' to the console.    
