// Creating objects
let person = { name: "Alice", age: 30, city: "New York" }; // This is an object declaration and initialization. The object 'person' has three properties: 'name', 'age', and 'city'.
console.log(person); // This will output the object 'person' to the console.    
// Accessing object properties
console.log(person.name); // This will output the string "Alice" to the console, which is the value of the 'name' property of the object 'person'.
console.log(person.age); // This will output the number 30 to the console, which is the value of the 'age' property of the object 'person'.
console.log(person.city); // This will output the string "New York" to the console, which is the value of the 'city' property of the object 'person'.

// Modifying object properties
person.name = "Bob"; // This will change the value of the 'name' property of the object 'person' to "Bob".
console.log(person); // This will output the string "Bob" to the console, which is the updated value of the 'name' property of the object 'person'.
console.log(person.name);